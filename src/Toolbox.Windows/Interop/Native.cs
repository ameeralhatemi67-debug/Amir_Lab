    /// <summary>True while the physical button that acts as the primary (or secondary) mouse button is down.</summary>
    public static bool IsDragButtonDown()
    {
        // GetAsyncKeyState reports physical buttons; honour the "swap buttons" accessibility setting.
        bool swapped = GetSystemMetrics(SM_SWAPBUTTON) != 0;
        int primary = swapped ? VK_RBUTTON : VK_LBUTTON;
        int secondary = swapped ? VK_LBUTTON : VK_RBUTTON;
        // Explorer also supports right-button drags (they end with a context menu at the target).
        return (GetAsyncKeyState(primary) & 0x8000) != 0 || (GetAsyncKeyState(secondary) & 0x8000) != 0;
    }

    /// <summary>
    /// Posts a zero-distance mouse move so the OLE drag loop re-evaluates the window under the
    /// pointer and delivers DragEnter to a window that has just appeared there.
    /// </summary>
    public static void NudgePointer()
    {
        var inputs = new INPUT[1];
        inputs[0].type = INPUT_MOUSE;
        inputs[0].u.mi = new MOUSEINPUT { dx = 0, dy = 0, dwFlags = MOUSEEVENTF_MOVE };
        SendInput(1, inputs, Marshal.SizeOf<INPUT>());
    }
